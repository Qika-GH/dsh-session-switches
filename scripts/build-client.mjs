/*
 * build-client.mjs — turn the CommonJS client source into the module shell the
 * DSH renderer expects.
 *
 * There is no bundler in this profile (no esbuild, no typescript), and the
 * client's only runtime import is react, which the renderer hands to the
 * factory. So "building" is wrapping: read src/client/index.js and emit
 * window.__ModuleLoader__.load({ id, factory }) around it. No minification, so
 * a stack trace still points at the line you wrote.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const packageName = 'dsh-session-switches'

const source = readFileSync(join(root, 'src/client/index.js'), 'utf8')
const indented = source.split('\n').map(line => (line ? '    ' + line : line)).join('\n')

const head = [
  '/* Generated by scripts/build-client.mjs - do not edit. */',
  'window.__ModuleLoader__.load({',
  '  id: ' + JSON.stringify(packageName) + ',',
  '  factory: (require) => {',
  '    var module = { exports: {} };',
  '    var exports = module.exports;',
]
const tail = [
  '    return module.exports;',
  '  },',
  '});',
  '',
]

const bundle = head.concat([indented]).concat(tail).join('\n')
const outDir = join(root, 'lib/client')
mkdirSync(outDir, { recursive: true })
const outFile = join(outDir, 'index.js')
writeFileSync(outFile, bundle, 'utf8')
console.log('wrote ' + outFile + ' (' + Buffer.byteLength(bundle) + ' bytes)')